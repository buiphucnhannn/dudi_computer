export function getDefaultArticleBySlug(slug) {
  if (!slug) return null;
  
  // Direct match
  let found = DEFAULT_ARTICLES.find((item) => item.slug === slug);

  // Normalize / Fuzzy match for common slug variations
  if (!found) {
    const cleanSlug = slug.toLowerCase().replace(/[^a-z0-9]/g, "");
    found = DEFAULT_ARTICLES.find((item) => {
      const itemClean = item.slug.toLowerCase().replace(/[^a-z0-9]/g, "");
      return itemClean === cleanSlug || itemClean.includes(cleanSlug) || cleanSlug.includes(itemClean);
    });
  }

  if (found) {
    const related = DEFAULT_ARTICLES.filter((item) => item.slug !== found.slug);
    return { article: found, related };
  }
  
  return null;
}
